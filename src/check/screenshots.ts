/**
 * Headless screenshots: a Flutter widget test that renders each screen to a PNG with real fonts,
 * so the Check stage works with no emulator or device. The PNGs double as store screenshot drafts
 * (430×932 @3x = 1290×2796, the App Store 6.7"/6.9" size class).
 */
export const SCREENSHOT_TEST_FILE = "test/p2s_screenshots_test.dart";

export function screenshotTestSource(packageName: string): string {
  return `// Generated by prompt-to-store. Renders every screen to a PNG — no emulator needed.
// Run by the \`check_run\` tool. Keep the SCREENS list up to date with the app's screens.
import 'dart:convert';
import 'dart:io';
import 'dart:ui' as ui;

import 'package:flutter/material.dart';
import 'package:flutter/rendering.dart';
import 'package:flutter/services.dart';
import 'package:flutter_test/flutter_test.dart';

import 'package:${packageName}/main.dart';

/// One entry per screen. Build each screen directly (with sample data) so it can be
/// captured without navigating. Wrap non-app widgets in MaterialApp(theme: ...).
final Map<String, Widget Function()> screens = {
  '01_home': () => const MyApp(),
};

/// Logical size and pixel ratio for each device class.
const Map<String, (Size, double)> devices = {
  'phone': (Size(430, 932), 3.0),
};

Future<void> _loadFonts() async {
  final root = Platform.environment['FLUTTER_ROOT'];
  if (root != null) {
    final dir = Directory('\$root/bin/cache/artifacts/material_fonts');
    if (dir.existsSync()) {
      final roboto = FontLoader('Roboto');
      final icons = FontLoader('MaterialIcons');
      for (final f in dir.listSync().whereType<File>()) {
        final name = f.uri.pathSegments.last.toLowerCase();
        final bytes = f.readAsBytes().then((b) => ByteData.view(b.buffer));
        if (name.startsWith('roboto') && name.endsWith('.ttf')) roboto.addFont(bytes);
        if (name.startsWith('materialicons')) icons.addFont(bytes);
      }
      await roboto.load();
      await icons.load();
    }
  }
  // Fonts declared in pubspec.yaml (including CupertinoIcons).
  try {
    final manifest = json.decode(await rootBundle.loadString('FontManifest.json')) as List<dynamic>;
    for (final family in manifest) {
      final loader = FontLoader(family['family'] as String);
      for (final font in family['fonts'] as List<dynamic>) {
        loader.addFont(rootBundle.load(font['asset'] as String));
      }
      await loader.load();
    }
  } catch (_) {}
}

void main() {
  final outDir = Platform.environment['P2S_SCREENSHOT_DIR'] ?? '../.prompt-to-store/checks/screens';

  setUpAll(() async {
    await _loadFonts();
  });

  for (final device in devices.entries) {
    for (final screen in screens.entries) {
      testWidgets('screenshot \${device.key}/\${screen.key}', (tester) async {
        debugDisableShadows = false;
        WidgetsApp.debugAllowBannerOverride = false; // no DEBUG ribbon
        final (size, ratio) = device.value;
        tester.view.physicalSize = size * ratio;
        tester.view.devicePixelRatio = ratio;
        addTearDown(tester.view.reset);

        await tester.pumpWidget(RepaintBoundary(key: const ValueKey('p2s-root'), child: screen.value()));
        try {
          await tester.pumpAndSettle(const Duration(milliseconds: 100), EnginePhase.sendSemanticsUpdate, const Duration(seconds: 5));
        } catch (_) {
          await tester.pump(const Duration(seconds: 1)); // endless animations (spinners)
        }
        final boundary = tester.renderObject<RenderRepaintBoundary>(find.byKey(const ValueKey('p2s-root')));
        await tester.runAsync(() async {
          final image = await boundary.toImage(pixelRatio: ratio);
          final bytes = await image.toByteData(format: ui.ImageByteFormat.png);
          final file = File('\$outDir/\${device.key}/\${screen.key}.png');
          file.parent.createSync(recursive: true);
          file.writeAsBytesSync(bytes!.buffer.asUint8List());
        });
        debugDisableShadows = true;
      });
    }
  }
}
`;
}
