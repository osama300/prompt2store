/**
 * Generates codemagic.yaml for a Flutter project. Workflows (ids are stable — tools refer to them):
 *  - p2s-android-test : release APK signed with the debug key → email + public link. No store accounts.
 *  - p2s-ios-simulator: iOS Simulator .app (zip). No Apple account. Proves iOS compiles.
 *  - p2s-android-release: signed AAB for Google Play (upload key from the p2s_android_signing group).
 *  - p2s-ios-release : signed IPA uploaded to TestFlight (credentials from the p2s_app_store group).
 * Credentials reach Codemagic through variable groups created by the tools; they never pass through chat.
 */
export const WF = {
  androidTest: "p2s-android-test",
  iosSimulator: "p2s-ios-simulator",
  androidRelease: "p2s-android-release",
  iosRelease: "p2s-ios-release",
} as const;

export const GROUPS = { androidSigning: "p2s_android_signing", appStore: "p2s_app_store" } as const;

export const YAML_MARKER = "# managed-by: prompt-to-store";

export interface YamlOpts {
  bundleId: string;
  emails: string[];
  /** Subdirectory of the repo that contains pubspec.yaml ("" for repo root). */
  workingDirectory?: string;
}

export function codemagicYaml(o: YamlOpts): string {
  const wd = o.workingDirectory ? `\n    working_directory: ${o.workingDirectory}` : "";
  const email = o.emails.length
    ? `
    publishing:
      email:
        recipients:
${o.emails.map((e) => `          - ${e}`).join("\n")}
        notify:
          success: true
          failure: true`
    : "";
  // Codemagic resolves artifact globs from the clone root; list both forms when a working_directory is used.
  const art = (glob: string) => (o.workingDirectory ? `      - ${glob}\n      - ${o.workingDirectory}/${glob}` : `      - ${glob}`);
  return `${YAML_MARKER}
# Generated by prompt-to-store (https://github.com/osama300/prompt2store).
# Builds are started through the API by your coding agent; there are no push triggers.
# You can edit this file — keep the workflow ids so the tools can find them.

definitions:
  env: &env
    flutter: stable
    java: 17
  cache: &cache
    cache_paths:
      - $HOME/.pub-cache
      - $HOME/.gradle/caches

workflows:
  ${WF.androidTest}:
    name: Android test build (APK)${wd}
    instance_type: mac_mini_m2
    max_build_duration: 45
    environment:
      <<: *env
    cache: *cache
    scripts:
      - name: Get packages
        script: flutter pub get
      - name: Analyze
        script: flutter analyze --no-fatal-infos --no-fatal-warnings
      - name: Build APK (signed with the debug key — installable test build)
        script: flutter build apk --release --build-number=$BUILD_NUMBER
    artifacts:
${art("build/**/outputs/**/*.apk")}${email}

  ${WF.iosSimulator}:
    name: iOS simulator build${wd}
    instance_type: mac_mini_m2
    max_build_duration: 45
    environment:
      flutter: stable
      xcode: latest
      cocoapods: default
    scripts:
      - name: Get packages
        script: flutter pub get
      - name: Build for the iOS Simulator (no Apple account needed)
        script: |
          flutter build ios --simulator --debug
          cd build/ios/iphonesimulator && zip -qr ../../../Runner-simulator.zip Runner.app
    artifacts:
${art("Runner-simulator.zip")}${email}

  ${WF.androidRelease}:
    name: Android release (AAB for Google Play)${wd}
    instance_type: mac_mini_m2
    max_build_duration: 60
    environment:
      <<: *env
      groups:
        - ${GROUPS.androidSigning}
    cache: *cache
    scripts:
      - name: Get packages
        script: flutter pub get
      - name: Upload key
        script: |
          echo "$P2S_KEYSTORE_B64" | base64 --decode > "$CM_BUILD_DIR/p2s-upload.p12"
          cat > android/key.properties <<EOF
          storePassword=$P2S_KEYSTORE_PASSWORD
          keyPassword=$P2S_KEYSTORE_PASSWORD
          keyAlias=$P2S_KEY_ALIAS
          storeFile=$CM_BUILD_DIR/p2s-upload.p12
          EOF
      - name: Build AAB
        script: flutter build appbundle --release --build-number=$BUILD_NUMBER
    artifacts:
${art("build/**/outputs/**/*.aab")}
${art("build/**/outputs/**/mapping.txt")}${email}

  ${WF.iosRelease}:
    name: iOS release (TestFlight)${wd}
    instance_type: mac_mini_m2
    max_build_duration: 60
    environment:
      flutter: stable
      xcode: latest
      cocoapods: default
      groups:
        - ${GROUPS.appStore}
      vars:
        BUNDLE_ID: "${o.bundleId}"
    scripts:
      - name: Signing (certificates and profiles created via the App Store Connect API)
        script: |
          keychain initialize
          app-store-connect fetch-signing-files "$BUNDLE_ID" --type IOS_APP_STORE --certificate-key=@env:CERTIFICATE_PRIVATE_KEY --create
          keychain add-certificates
          xcode-project use-profiles
      - name: Get packages
        script: |
          flutter pub get
          find . -name Podfile -execdir pod install \\;
      - name: Build IPA
        script: |
          LATEST=$(app-store-connect get-latest-testflight-build-number "$APP_STORE_APP_ID" 2>/dev/null || echo 0)
          flutter build ipa --release --build-number=$((LATEST + 1)) --export-options-plist=/Users/builder/export_options.plist
    artifacts:
${art("build/ios/ipa/*.ipa")}
      - /tmp/xcodebuild_logs/*.log
    publishing:
      app_store_connect:
        api_key: $APP_STORE_CONNECT_PRIVATE_KEY
        key_id: $APP_STORE_CONNECT_KEY_IDENTIFIER
        issuer_id: $APP_STORE_CONNECT_ISSUER_ID
        submit_to_testflight: true
`;
}
